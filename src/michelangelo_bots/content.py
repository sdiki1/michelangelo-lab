ACTION_TEXTS: dict[Action, str] = {
    Action.ABOUT: ABOUT_TEXT,
    Action.DELIVERY: DELIVERY_TEXT,
    Action.CONTACTS: CONTACTS_TEXT,
    Action.TRACKING: TRACKING_TEXT,
    Action.MAIN_MENU: START_TEXT,
}


def main_menu_buttons(miniapp_url: str) -> list[MenuButton]:
    return [
        MenuButton("Миниапп", url=miniapp_url),
        MenuButton("О нас", action=Action.ABOUT),
        MenuButton("Доставка кукол бабочек", action=Action.DELIVERY),
        MenuButton("Наши контакты", action=Action.CONTACTS),
        MenuButton("Как отслеживать доставку", action=Action.TRACKING),
    ]


def back_to_main_buttons() -> list[MenuButton]:
    return [MenuButton("В главное меню", action=Action.MAIN_MENU)]


def text_for_action(action: Action) -> str:
    return ACTION_TEXTS[action]


def render_start_text(name: str | None) -> str:
    safe_name = (name or "").strip() or "дорогой друг"
    return START_TEXT.replace("{{name}}", safe_name)
