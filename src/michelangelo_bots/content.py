from dataclasses import dataclass
from enum import StrEnum


class Action(StrEnum):
    ABOUT = "about"
    DELIVERY = "delivery"
    CONTACTS = "contacts"
    TRACKING = "tracking"
    MAIN_MENU = "main_menu"


@dataclass(frozen=True)
class MenuButton:
    title: str
    action: Action | str | None = None
    url: str | None = None
    web_app: bool = True


